CREATE TABLE IF NOT EXISTS studies (
    nct_id TEXT PRIMARY KEY CHECK (nct_id ~ '^NCT[0-9]{8}$'),
    title TEXT NOT NULL,
    overall_status TEXT NOT NULL,
    conditions_json TEXT NOT NULL CHECK (conditions_json IS JSON ARRAY),
    phases_json TEXT NOT NULL CHECK (phases_json IS JSON ARRAY),
    source_description TEXT,
    brief_summary TEXT,
    detailed_description TEXT,
    eligibility_criteria TEXT,
    minimum_age TEXT,
    maximum_age TEXT,
    sex TEXT,
    locations_json TEXT NOT NULL CHECK (locations_json IS JSON ARRAY),
    contacts_json TEXT NOT NULL CHECK (contacts_json IS JSON ARRAY),
    source_url TEXT NOT NULL,
    retrieved_at TEXT NOT NULL,
    source_hash TEXT NOT NULL CHECK (source_hash ~ '^[a-f0-9]{64}$'),
    raw_json TEXT NOT NULL CHECK (raw_json IS JSON OBJECT),
    detail_status TEXT NOT NULL DEFAULT 'not_retrieved'
        CHECK (detail_status IN ('not_retrieved', 'retrieved', 'retrieval_failed')),
    detail_attempted_at TEXT,
    detail_error_code TEXT
);
CREATE INDEX IF NOT EXISTS idx_studies_status_nct ON studies(overall_status, nct_id);
CREATE INDEX IF NOT EXISTS idx_studies_title ON studies(title);

CREATE TABLE IF NOT EXISTS ingestion_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_url TEXT NOT NULL,
    effective_page_size INTEGER NOT NULL DEFAULT 20 CHECK (effective_page_size BETWEEN 1 AND 1000),
    pagination_completed INTEGER NOT NULL DEFAULT 0 CHECK (pagination_completed IN (0, 1)),
    started_at TEXT NOT NULL,
    index_retrieved_at TIMESTAMPTZ,
    published_at TIMESTAMPTZ,
    completed_at TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('complete', 'partial', 'failed')),
    page_count INTEGER NOT NULL CHECK (page_count >= 0),
    raw_record_count INTEGER NOT NULL CHECK (raw_record_count >= 0),
    accepted_record_count INTEGER NOT NULL CHECK (accepted_record_count >= 0),
    duplicate_identifier_count INTEGER NOT NULL CHECK (duplicate_identifier_count >= 0),
    missing_value_counts_json TEXT NOT NULL CHECK (missing_value_counts_json IS JSON OBJECT),
    excluded_records_json TEXT NOT NULL CHECK (excluded_records_json IS JSON ARRAY),
    errors_json TEXT NOT NULL CHECK (errors_json IS JSON ARRAY),
    detail_requested_count INTEGER NOT NULL CHECK (detail_requested_count >= 0),
    detail_retrieved_count INTEGER NOT NULL CHECK (detail_retrieved_count >= 0),
    index_retrieved_count INTEGER NOT NULL DEFAULT 0 CHECK (index_retrieved_count >= 0),
    detail_cache_hit_count INTEGER NOT NULL DEFAULT 0 CHECK (detail_cache_hit_count >= 0),
    detail_network_count INTEGER NOT NULL DEFAULT 0 CHECK (detail_network_count >= 0),
    detail_resumed_count INTEGER NOT NULL DEFAULT 0 CHECK (detail_resumed_count >= 0),
    detail_failed_count INTEGER NOT NULL DEFAULT 0 CHECK (detail_failed_count >= 0),
    incomplete_detail_ids_json TEXT NOT NULL DEFAULT '[]' CHECK (incomplete_detail_ids_json IS JSON ARRAY),
    ma_verified_count INTEGER NOT NULL DEFAULT 0 CHECK (ma_verified_count >= 0),
    ma_unverified_count INTEGER NOT NULL DEFAULT 0 CHECK (ma_unverified_count >= 0),
    ma_unverified_records_json TEXT NOT NULL DEFAULT '[]' CHECK (ma_unverified_records_json IS JSON ARRAY),
    request_count INTEGER NOT NULL DEFAULT 0 CHECK (request_count >= 0),
    retry_count INTEGER NOT NULL DEFAULT 0 CHECK (retry_count >= 0),
    rate_limited_count INTEGER NOT NULL DEFAULT 0 CHECK (rate_limited_count >= 0),
    cohort_fingerprint TEXT CHECK (cohort_fingerprint IS NULL OR cohort_fingerprint ~ '^[a-f0-9]{64}$'),
    checkpoint_resumed INTEGER NOT NULL DEFAULT 0 CHECK (checkpoint_resumed IN (0, 1)),
    publication_attempted INTEGER NOT NULL DEFAULT 0 CHECK (publication_attempted IN (0, 1)),
    publication_completed INTEGER NOT NULL DEFAULT 0 CHECK (publication_completed IN (0, 1)),
    published_record_count INTEGER NOT NULL DEFAULT 0 CHECK (published_record_count >= 0),
    previous_snapshot_preserved INTEGER NOT NULL DEFAULT 0 CHECK (previous_snapshot_preserved IN (0, 1)),
    CONSTRAINT ingestion_publication_consistent CHECK (
        (publication_completed = 0 AND published_record_count = 0)
        OR
        (publication_completed = 1 AND status = 'complete'
         AND published_record_count = accepted_record_count)
    )
);
CREATE INDEX IF NOT EXISTS idx_ingestion_runs_completed ON ingestion_runs(completed_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS criteria (
    criterion_id TEXT PRIMARY KEY,
    nct_id TEXT NOT NULL REFERENCES studies(nct_id) ON DELETE CASCADE,
    extraction_method TEXT NOT NULL,
    payload_json TEXT NOT NULL CHECK (payload_json IS JSON OBJECT)
);
CREATE INDEX IF NOT EXISTS idx_criteria_nct ON criteria(nct_id, extraction_method);

CREATE TABLE IF NOT EXISTS extraction_cache (
    cache_key TEXT PRIMARY KEY,
    nct_id TEXT NOT NULL REFERENCES studies(nct_id) ON DELETE CASCADE,
    source_hash TEXT NOT NULL CHECK (source_hash ~ '^[a-f0-9]{64}$'),
    provider TEXT NOT NULL,
    model TEXT NOT NULL,
    payload_json TEXT NOT NULL CHECK (payload_json IS JSON OBJECT),
    created_at TEXT NOT NULL,
    coverage_verified INTEGER NOT NULL DEFAULT 0 CHECK (coverage_verified IN (0, 1)),
    coverage_verification_method TEXT,
    coverage_verified_at TEXT,
    CONSTRAINT extraction_coverage_verification_consistent CHECK (
        (coverage_verified = 0 AND coverage_verification_method IS NULL AND coverage_verified_at IS NULL)
        OR
        (coverage_verified = 1 AND coverage_verification_method IN (
            'manual_protocol_review', 'deterministic_test_fixture'
        ) AND coverage_verified_at IS NOT NULL)
    )
);
CREATE INDEX IF NOT EXISTS idx_extraction_cache_nct ON extraction_cache(nct_id);
CREATE INDEX IF NOT EXISTS idx_extraction_cache_current
    ON extraction_cache(nct_id, source_hash, created_at DESC);

CREATE TABLE IF NOT EXISTS extraction_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nct_id TEXT NOT NULL REFERENCES studies(nct_id) ON DELETE CASCADE,
    source_hash TEXT NOT NULL CHECK (source_hash ~ '^[a-f0-9]{64}$'),
    provider TEXT NOT NULL,
    model TEXT NOT NULL,
    schema_version TEXT NOT NULL,
    prompt_version TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('accepted', 'failed')),
    error TEXT,
    created_at TEXT NOT NULL,
    CONSTRAINT extraction_attempt_status_error CHECK (
        (status = 'accepted' AND error IS NULL) OR status = 'failed'
    )
);
CREATE INDEX IF NOT EXISTS idx_extraction_attempts_current
    ON extraction_attempts(nct_id, source_hash, created_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS summary_cache (
    cache_key TEXT PRIMARY KEY,
    nct_id TEXT NOT NULL REFERENCES studies(nct_id) ON DELETE CASCADE,
    source_hash TEXT NOT NULL CHECK (source_hash ~ '^[a-f0-9]{64}$'),
    provider TEXT NOT NULL,
    model TEXT NOT NULL,
    schema_version TEXT NOT NULL,
    prompt_version TEXT NOT NULL,
    payload_json TEXT NOT NULL CHECK (payload_json IS JSON OBJECT),
    created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_summary_cache_current
    ON summary_cache(nct_id, source_hash, created_at DESC);
